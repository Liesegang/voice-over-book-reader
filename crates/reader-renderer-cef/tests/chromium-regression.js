(async () => {
    const assert=(condition,message)=>{if(!condition)throw Error(message);};
    const b=globalThis.__vobrBook;
    const options={flow:'reflowable',writing:'author',margins:[48,60,48,60],font_family:null,font_size:null,line_height:null,letter_spacing:null,ruby_scale:null,show_ruby:true,fixed_viewport:null};
    const beforeIds=b.testing.originalNodes.length;
    await b.dispatch({type:'configure',revision:10,chapter:3,nodes:[],options});
    let events=b.drain();
    assert(!events.some(e=>e.type==='error'),JSON.stringify(events));
    const pagination=events.find(e=>e.type==='pagination');
    assert(pagination?.pages>=5,'Expected a long chapter with at least five pages');
    assert(pagination.page_starts.length===pagination.pages,'Every confirmed page has an index');
    assert(pagination.writing_mode==='vertical-rl','Author vertical writing must survive');
    const start=pagination.page_starts[2];assert(start,'Page three source start missing');
    const source=b.testing.originalNodes.find(n=>n.node===start.node);
    assert(source?.parts,'Page source must be original text, not container');
    const utf16=b.testing.toUtf16(source.text,start.offset);
    const end=start.offset+b.testing.byteLength(String.fromCodePoint(source.text.codePointAt(utf16)));
    const range={chapter:3,node:start.node,start:start.offset,end};
    await b.dispatch({type:'page',revision:10,index:2});
    await b.dispatch({type:'rects',revision:10,ranges:[range]});
    events=b.drain();const rect=events.find(e=>e.type==='rects')?.rects[0];
    assert(rect?.width>0&&rect.height>0,'Mapped glyph must have rendered geometry');
    assert(rect.x>=0&&rect.x+rect.width<=innerWidth+1&&rect.y>=0&&rect.y+rect.height<=innerHeight+1,'Page-start glyph must be inside current viewport');
    await b.dispatch({type:'hit_test',revision:10,x:rect.x+rect.width/2,y:rect.y+rect.height/2});
    events=b.drain();const hit=events.find(e=>e.type==='hit')?.location;
    assert(hit?.node===start.node&&hit.offset>=start.offset&&hit.offset<=end,'Hit test must return the mapped source glyph');
    await b.dispatch({type:'highlight',revision:10,ranges:[range]});
    assert(CSS.highlights.get('vobr-speech')?.size===1,'Speech range must use CSS Highlight');
    assert(b.testing.originalNodes.length===beforeIds,'Native styles must not renumber source nodes');
    const cdata=b.testing.originalNodes.find(n=>n.text==='前😀後');
    assert(cdata?.parts.length===3,'Text/CDATA/Text must map to one virtual source node');
    await b.dispatch({type:'locate',revision:10,location:{chapter:3,node:cdata.node,offset:3}});
    await b.dispatch({type:'rects',revision:10,ranges:[{chapter:3,node:cdata.node,start:3,end:7}]});
    events=b.drain();const emoji=events.find(e=>e.type==='rects')?.rects[0];
    assert(emoji?.width>0&&emoji.height>0,'UTF-8 byte range must resolve a physical CDATA emoji');
    const selected=docSelection();
    function docSelection(){const r=document.createRange();r.setStart(cdata.parts[1].dom,0);r.setEnd(cdata.parts[1].dom,2);const s=document.getSelection();s.removeAllRanges();s.addRange(r);return s;}
    await b.dispatch({type:'selection',revision:10});
    const selection=b.drain().find(e=>e.type==='selection');
    assert(selection?.start?.node===cdata.node&&selection.start.offset===3&&selection.end.offset===7,'CDATA DOM selection must return virtual-node UTF-8 byte offsets');
    assert(selection.text==='😀','Selected CDATA text must survive Chromium Selection string omissions');
    selected.removeAllRanges();
    await b.dispatch({type:'page',revision:9,index:4});
    assert(b.drain().length===0,'Stale revisions cannot move the current page');
    await b.dispatch({type:'page',revision:10,index:0});b.drain();
    document.querySelector('p').setAttribute('class','author-change');
    await new Promise(resolve=>setTimeout(resolve,30));
    assert(b.drain().some(e=>e.type==='invalidated'&&e.reason==='author_document_mutated'),'Author geometry mutation must invalidate counts');
    await b.dispatch({type:'configure',revision:11,chapter:3,nodes:[],options});
    events=b.drain();assert(events.some(e=>e.type==='pagination'&&e.revision===11),'New revision must reconfirm pagination');
    console.log('NAV_REGRESSION PASS '+JSON.stringify({pages:pagination.pages,sourceNodes:beforeIds,start,hit,rect,cdataNode:cdata.node,cdataParts:cdata.parts.length,emoji,selection}));
})().catch(error=>console.error('NAV_REGRESSION FAIL '+error.stack));
